import BubbleEngine
import Foundation

// Plays every level with the bot and prints LevelPar.generated.swift.
// Usage: swift run -c release bubble-par > Sources/BubbleEngine/LevelPar.generated.swift
//        swift run -c release bubble-par --stats   (summary only)
let statsOnly = CommandLine.arguments.contains("--stats")
let limit = CommandLine.arguments.firstIndex(of: "--count").map { Int(CommandLine.arguments[$0 + 1])! } ?? LevelCatalog.count
var pars: [Int] = []
var variants: [Int] = []
var counts: [Int] = []
let start = Date()
for n in 1...limit {
    let result = LevelCatalog.calibrate(n)
    pars.append(result.par)
    variants.append(result.variant)
    counts.append(LevelCatalog.layout(n, variant: result.variant).grid.count)
}
let elapsed = Date().timeIntervalSince(start)
func describe(_ values: [Int]) -> String {
    let sorted = values.sorted()
    return "min \(sorted.first!) median \(sorted[sorted.count / 2]) max \(sorted.last!)"
}
if statsOnly {
    print("levels: \(limit) in \(String(format: "%.1f", elapsed))s")
    print("par: \(describe(pars))")
    print("bubbles: \(describe(counts))")
    let outside = (0..<limit).filter { !(LevelCatalog.minimumPar(for: $0 + 1)...LevelCatalog.maximumPar).contains(pars[$0]) }
    print("variant > 0: \(variants.filter { $0 > 0 }.count), max variant \(variants.max()!), outside par range: \(outside.count) \(outside.prefix(10).map { $0 + 1 })")
    var patterns: [String: Int] = [:], colorings: [String: Int] = [:]
    for n in 1...limit {
        let l = LevelCatalog.layout(n, variant: variants[n - 1])
        patterns[l.pattern, default: 0] += 1
        colorings[l.coloring, default: 0] += 1
    }
    print("patterns: \(patterns.sorted { $0.value > $1.value }.map { "\($0.key) \($0.value)" }.joined(separator: ", "))")
    print("colorings: \(colorings.sorted { $0.value > $1.value }.map { "\($0.key) \($0.value)" }.joined(separator: ", "))")
    for chunk in stride(from: 0, to: limit, by: max(1, limit / 10)) {
        let slice = chunk..<min(limit, chunk + max(1, limit / 10))
        let p = slice.map { pars[$0] }, c = slice.map { counts[$0] }
        print("levels \(slice.lowerBound + 1)-\(slice.upperBound): par avg \(p.reduce(0, +) / p.count), bubbles avg \(c.reduce(0, +) / c.count)")
    }
} else {
    precondition(pars.allSatisfy { $0 <= 255 } && variants.allSatisfy { $0 <= 255 })
    func rows(_ values: [Int]) -> String {
        stride(from: 0, to: values.count, by: 25).map { i in
            "        " + values[i..<min(values.count, i + 25)].map(String.init).joined(separator: ", ") + ","
        }.joined(separator: "\n")
    }
    print("""
    // Generated by `swift run -c release bubble-par` in Packages/BubbleEngine. Do not edit by hand.
    // For each level: the shots the bot needed (par) and which generated variant it cleared.
    enum LevelPar {
        static let par: [UInt8] = [
    \(rows(pars))
        ]
        static let variant: [UInt8] = [
    \(rows(variants))
        ]
    }
    """)
}
